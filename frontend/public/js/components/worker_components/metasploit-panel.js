// metasploit control panel. Unlike every other tool's panel here, this one
// is NOT a scan-flags-then-run-to-completion UI: msfconsole is a long-lived,
// interactive console. The buttons below only cover msfconsole's own launch
// flags (-q, -r, -x, ...), confirmed live against "msfconsole -h" and
// grouped the way that help text groups them (COMMON, DATABASE, FRAMEWORK,
// MODULE, CONSOLE). Clicking "Send" on this worker's control panel launches
// msfconsole with those flags; the actual work -- `use`, `set`, `run`,
// `exploit`, `search`, and every other msfconsole command -- happens by
// typing straight into live-terminal.js's input box afterward, which
// reaches the running console through this worker's existing /input route,
// exactly like answering a sqlmap or hydra prompt.
//
// A flag marked isFile expects an existing file (a resource script, a
// config file, a YAML database settings file) rather than an arbitrary
// typed value — for those, clicking the flag opens an expandable list of
// whatever's actually saved in the selected profile's Project Folder (see
// projectFolder.js) instead of a plain text popup.
